/**
 * Bundles Night Session scoped CSS into a TS module for the preview JS bundle.
 * Keep in sync with src/package/styles.css Night Session @import block.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const NIGHT_SESSION_STYLE_FILES = [
  "src/templates/variants/nightSession/styles/night-session-shared.css",
  "src/templates/variants/nightSession/styles/night-session-intro.css",
  "src/templates/variants/nightSession/styles/night-session-broadcast.css",
  "src/templates/variants/nightSession/styles/night-session-results.css",
  "src/templates/variants/nightSession/styles/night-session-result-single.css",
  "src/templates/variants/nightSession/styles/night-session-upcoming.css",
  "src/templates/variants/nightSession/styles/night-session-ladder.css",
  "src/templates/variants/nightSession/styles/night-session-top5.css",
  "src/templates/variants/nightSession/styles/night-session-performances.css",
  "src/templates/variants/nightSession/styles/night-session-team-roster.css",
  "src/templates/variants/nightSession/styles/night-session-team-of-the-week.css",
];

const outDir = join(root, "src/package/generated");
const outFile = join(outDir, "nightSessionBundledCss.ts");

const cssParts = NIGHT_SESSION_STYLE_FILES.map((rel) => {
  const abs = join(root, rel);
  const content = readFileSync(abs, "utf8");
  return `/* ${rel} */\n${content}`;
});

const bundledCss = cssParts.join("\n\n");

if (!bundledCss.includes(".night-session-canvas")) {
  console.error(
    "inline-night-session-css: bundled CSS missing .night-session-canvas",
  );
  process.exit(1);
}

const escaped = bundledCss
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

mkdirSync(outDir, { recursive: true });

writeFileSync(
  outFile,
  `/** Auto-generated by scripts/inline-night-session-css.mjs — do not edit. */\nexport const NIGHT_SESSION_BUNDLED_CSS = \`${escaped}\`;\n`,
  "utf8",
);

console.log(
  `inline-night-session-css: wrote ${outFile} (${bundledCss.length} bytes)`,
);
