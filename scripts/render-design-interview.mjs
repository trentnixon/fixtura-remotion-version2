/** Render the interview's Markdown content into its existing HTML page shell. */
import fs from "node:fs";
import { renderInterviewMarkdown } from "../design/_shared/lib/interview-markdown.js";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(
  path.join(root, "design/.docs/design-interview-prompt.md"),
  "utf8",
);
const target = path.join(root, "design/interview/index.html");
const page = fs.readFileSync(target, "utf8");
const content = renderInterviewMarkdown(source);
const start = page.indexOf('<article class="design-guide">');
const end = page.indexOf("</article>", start);
if (start < 0 || end < 0)
  throw new Error("Interview page shell missing article");
const contentStart = start + '<article class="design-guide">'.length;
const rendered =
  page.slice(0, contentStart) +
  "\n<!-- Content generated by scripts/render-design-interview.mjs. Edit the Markdown source. -->\n" +
  content +
  "\n" +
  page.slice(end);
if (process.argv.includes("--check")) {
  if (page.replace(/\r\n/g, "\n") !== rendered.replace(/\r\n/g, "\n")) {
    console.error(
      "Interview HTML is stale. Run node scripts/render-design-interview.mjs.",
    );
    process.exitCode = 1;
  } else console.log("Interview HTML matches Markdown.");
} else {
  fs.writeFileSync(target, rendered);
  console.log("Updated design/interview/index.html");
}
