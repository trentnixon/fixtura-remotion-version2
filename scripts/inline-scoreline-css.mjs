/**
 * Bundles Scoreline scoped CSS into a TS module for the preview JS bundle.
 * Keeps file list in sync with src/package/styles.css @import block.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const SCORELINE_STYLE_FILES = [
  "src/templates/variants/scoreline/styles/scoreline-polish.css",
  "src/templates/variants/scoreline/styles/scoreline-results.css",
  "src/templates/variants/scoreline/styles/scoreline-result-single.css",
  "src/templates/variants/scoreline/styles/scoreline-upcoming.css",
  "src/templates/variants/scoreline/styles/scoreline-ladder.css",
  "src/templates/variants/scoreline/styles/scoreline-top5.css",
  "src/templates/variants/scoreline/styles/scoreline-performances.css",
  "src/templates/variants/scoreline/styles/scoreline-team-roster.css",
  "src/templates/variants/scoreline/styles/scoreline-team-of-the-week.css",
];

const outDir = join(root, "src/package/generated");
const outFile = join(outDir, "scorelineBundledCss.ts");

const cssParts = SCORELINE_STYLE_FILES.map((rel) => {
  const abs = join(root, rel);
  const content = readFileSync(abs, "utf8");
  return `/* ${rel} */\n${content}`;
});

const bundledCss = cssParts.join("\n\n");

if (!bundledCss.includes(".scoreline-canvas")) {
  console.error("inline-scoreline-css: bundled CSS missing .scoreline-canvas");
  process.exit(1);
}

const escaped = bundledCss
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

mkdirSync(outDir, { recursive: true });

writeFileSync(
  outFile,
  `/** Auto-generated by scripts/inline-scoreline-css.mjs — do not edit. */\nexport const SCORELINE_BUNDLED_CSS = \`${escaped}\`;\n`,
  "utf8",
);

console.log(
  `inline-scoreline-css: wrote ${outFile} (${bundledCss.length} bytes)`,
);
